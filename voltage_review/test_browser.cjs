const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1050}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const token=fs.readFileSync(process.argv[3],'utf8').trim();
 await page.goto(process.argv[2]+'/#'+token);
 await page.locator('#search').fill('tri_0003_1713794570204349518');
 await page.locator('#events button').first().click();
 await page.locator('summary').click();
 await page.locator('#points tr').first().waitFor();
 if(await page.locator('canvas.gpu').count()!==4)throw Error('Missing panels');
 const rendering=await page.evaluate(()=>[...document.querySelectorAll('canvas.gpu')].map(c=>({width:c.width,height:c.height,webgl:!!c.getContext('webgl2')})));
 if(rendering.some(c=>!c.webgl||!c.width||!c.height))throw Error('Missing WebGL rendering');
 await page.locator('#points input').first().check();
 await page.locator('#flag').click();await page.waitForFunction(()=>document.querySelector('#saved').textContent.startsWith('Saved revision 1'));
 await page.reload();await page.locator('#search').fill('tri_0003_1713794570204349518');await page.locator('#events button').first().click();
 await page.locator('summary').click();
 await page.locator('#points tr.flagged').first().waitFor();
 if(await page.locator('#points tr.flagged').count()!==1)throw Error('Flag did not persist');
 await page.locator('#points input').first().check();await page.locator('#restore').click();await page.waitForFunction(()=>document.querySelector('#saved').textContent.startsWith('Saved revision 2'));
 await page.locator('#undo').click();await page.waitForFunction(()=>document.querySelector('#saved').textContent.startsWith('Saved revision 3'));
 await page.screenshot({path:process.argv[4]+'/review_desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:process.argv[4]+'/review_mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Mobile overflow');
 console.log(JSON.stringify({rendering,errors,flags:await page.locator('#points tr.flagged').count()}));
 await browser.close();if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
