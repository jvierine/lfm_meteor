"""Audit and assemble saved minus-1000-day direct-fit ensembles for the paper.

Reuse immutable propagated samples, not obsolete WJ results. Local fit identity,
epoch, state origin, and review revision must agree with each saved snapshot.
Missing full chains and changed local input hashes are recorded, not concealed.
"""
from argparse import Namespace
import hashlib
import json
from pathlib import Path

import h5py
import numpy as np

from propagate_tristatic_orbits_1000d_classification import (
    jopek_williams_criteria, summarize_classification, write_outputs,
)

ROOT = Path(__file__).resolve().parent
CANONICAL = ROOT / 'results/tristatic_cached_shrinking_20261029'
OLD = ROOT / 'results/tristatic_shrinking_orbits_20261030'
REPAIR = ROOT / 'results/fit_repair_0035_0145_20261030/orbit'
PREVIOUS = ROOT / 'results/tristatic_shrinking_orbits_audited_20261107'
OUTPUT = ROOT / 'results/tristatic_shrinking_orbits_current_20261107'
CURRENT_SOURCES = OUTPUT / 'current_sources'
REFRESHED = OUTPUT / 'refreshed'
REJECTED = 'tri_0035_1713807353024349213'
REPAIRED = 'tri_0145_1713822124614349842'
FIELDS = ('valid', 'initial_e', 'a_au', 'e', 'i_deg', 'q_au', 'Q_au',
          'period_years', 'specific_energy_j_kg', 'tisserand_jupiter')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def bound_mask(ev):
    return (ev['valid'] & np.isfinite(ev['e']) & (ev['e'] < 1)
            & (ev['a_au'] > 0) & (ev['specific_energy_j_kg'] < 0)
            & np.isfinite(ev['i_deg']) & np.isfinite(ev['period_years']))


def write_classification_table(rows, path):
    lines = ['% Generated by assemble_current_orbit_products.py\n',
             '% Bound samples only; equal event weights; exclusions recorded in orbits.h5.\n',
             '\\begin{tabular}{llrr}\n\\toprule\n',
             'Criterion & Quantity & Cometary & Asteroidal \\\\\n\\midrule\n']
    for row in rows:
        lines.append(f"{row['symbol']} & {row['name']} & "
                     f"{100*row['cometary_event_mean_fraction']:.0f}\\% & "
                     f"{100*row['asteroidal_event_mean_fraction']:.0f}\\% \\\\\n")
    lines.append('\\bottomrule\n\\end{tabular}\n')
    path.write_text(''.join(lines))


def audit_snapshot(event, snapshot):
    folder = CURRENT_SOURCES/event if (CURRENT_SOURCES/event/'input.h5').exists() else CANONICAL/event
    plot = CURRENT_SOURCES/event/'plot.h5'
    with h5py.File(snapshot) as s, h5py.File(folder/'input.h5') as i, \
            h5py.File(folder/'fit.h5') as f, h5py.File(plot) as p:
        assert sha(folder/'fit.h5') == s.attrs['fit_sha256'], event
        assert 'shrinking' in f.attrs['model'] and f.attrs['optimizer_success'], event
        assert p.attrs['uncertainty_converged'], event
        assert s.attrs['uncertainty_method'] == p.attrs.get('uncertainty_method', 'conditional physical-model posterior'), event
        assert s.attrs['flag_revision'] == p.attrs['fit_flag_revision'], event
        flag = OUTPUT/'voltage_review_flags'/(event+'.h5')
        current_revision = 0
        if flag.exists():
            with h5py.File(flag) as flags:
                assert not flags.attrs.get('bad', False), event
                current_revision = int(flags.attrs['version'])
        assert current_revision == s.attrs['flag_revision'], event
        assert int(s['joint_fit/time_ns'][0]) == int(i['initial_detection_time_ns'][()]), event
        np.testing.assert_allclose(s['best_state_gcrs'][:],
                                   i['center'][:] + 1000*f['params'][:6], rtol=0, atol=1e-6)
        states = i['center'][:] + 1000*s['sample_params'][:, :6]
        np.testing.assert_allclose(states[:, :3], s['joint_fit/bootstrap_x_gcrs_m'][:, 0], rtol=0, atol=1e-6)
        np.testing.assert_allclose(states[:, 3:], s['joint_fit/bootstrap_v_gcrs_mps'][:, 0], rtol=0, atol=1e-6)
        source_status = []
        for name, expected in zip(json.loads(s.attrs['source_files']), json.loads(s.attrs['source_sha256'])):
            local = folder / Path(name).name
            status = 'missing' if not local.exists() else ('match' if sha(local) == expected else 'changed')
            assert status != 'changed', (event, local)
            source_status.append(status)
        return dict(snapshot_sha256=sha(snapshot), fit_sha256=sha(folder/'fit.h5'),
                    current_plot_sha256=sha(plot), current_plot=str(plot),
                    local_input_sha256=sha(folder/'input.h5'),
                    propagation_input_sha256=s.attrs['input_sha256'],
                    input_hash_matches=sha(folder/'input.h5') == s.attrs['input_sha256'],
                    source_status=json.dumps(source_status),
                    flag_revision=int(s.attrs['flag_revision']),
                    uncertainty_method=str(s.attrs['uncertainty_method']))


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with h5py.File(OUTPUT/'refresh_manifest.h5') as manifest:
        accepted = set(manifest['accepted_event_id'].asstr()[:])
        refreshed_ids = set(manifest['refreshed_event_id'].asstr()[:])
        assert len(accepted) == 232 and len(refreshed_ids) == 40
    events, audits, sources, snapshots = [], [], [], []
    with h5py.File(OLD/'orbits.h5') as old:
        assert old.attrs['days_back'] == 1000
        exclusions = list(zip(old['excluded_event_id'].asstr()[:], old['exclusion_reason'].asstr()[:]))
        exclusions.append((REJECTED, 'Rejected trajectory by event review; not a scientific orbit'))
        for index, event in enumerate(old['event_id'].asstr()[:]):
            if event == REJECTED:
                continue
            source = REPAIR/'tri_0145_orbit.h5' if event == REPAIRED else OLD/(event+'.h5')
            snapshot = (REPAIR if event == REPAIRED else OLD)/'inputs'/(event+'.h5')
            refreshed = (REFRESHED/(event+'.h5')).exists()
            assert refreshed == (event in refreshed_ids), event
            if refreshed:
                source = REFRESHED/(event+'.h5')
                snapshot = REFRESHED/'inputs'/(event+'.h5')
            audit = audit_snapshot(event, snapshot)
            with h5py.File(source) as h, h5py.File(snapshot) as s:
                assert h.attrs['event_id'] == event
                ev = {key: h[key][()] for key in FIELDS}
                ev.update(event_id=event, time_ns=int(h['time_ns'][()]))
                assert ev['time_ns'] == int(s['joint_fit/time_ns'][0])
                assert len(ev['e']) == len(s['sample_params']) == 100
                if event != REPAIRED and not refreshed:
                    for key in FIELDS:
                        np.testing.assert_equal(ev[key], old[key][index])
                assert np.all(ev['valid']) and np.isfinite(ev['e']).all()
                np.testing.assert_equal(ev['e'] < 1, ev['specific_energy_j_kg'] < 0)
            events.append(ev)
            audits.append(audit)
            sources.append(source)
            snapshots.append(snapshot)

    assert {ev['event_id'] for ev in events} == accepted

    classified = []
    probability = []
    for ev in events:
        bound = bound_mask(ev)
        if bound.any():
            selected = {k: v[bound] if isinstance(v, np.ndarray) else v for k, v in ev.items()}
            classified.append(selected)
            votes = jopek_williams_criteria(*(selected[k] for k in ('a_au', 'e', 'i_deg', 'period_years')))
            probability.append(np.mean(list(votes.values())))
        else:
            probability.append(np.nan)
    rows = summarize_classification(classified)
    args = Namespace(input_dir=CANONICAL, days_back=1000,
                     output_h5=OUTPUT/'orbits.h5', output_tex=OUTPUT/'classification.tex')
    write_outputs(events, rows, args)
    # Keep pooled-sample and equal-event statistics distinct in HDF5.
    write_classification_table(rows, args.output_tex)
    with h5py.File(args.output_h5, 'a') as h:
        h.attrs.update(model='direct shrinking radius', assembly_script=Path(__file__).name,
                       parent_sha256=sha(OLD/'orbits.h5'), repair_sha256=sha(REPAIR/'tri_0145_orbit.h5'),
                       input_events=len(list(CANONICAL.glob('tri_*'))), included_events=len(events),
                       classification_selection='Bound samples only; equal weight per event in table',
                       ephemeris='astropy builtin',
                       forces='Gravity only; no radiation pressure or atmospheric drag before first detection',
                       uncertainty='Conditional posterior, block bootstrap, or random-deletion robustness; not uniformly calibrated confidence intervals',
                       audit_limitations='Original remote input/fit/source hashes checked separately in remote_source_audit.h5; 40 currently selected bootstrap ensembles freshly propagated, remaining 192 verified saved ensembles reused. Physical systematics excluded.',
                       refreshed_events=40)
        dtype = h5py.string_dtype()
        for key, values in [('excluded_event_id', [x[0] for x in exclusions]),
                            ('exclusion_reason', [x[1] for x in exclusions]),
                            ('uncertainty_method', [x['uncertainty_method'] for x in audits])]:
            h.create_dataset(key, data=values, dtype=dtype)
        audit_group = h.create_group('source_audit')
        for ev, audit, source, snapshot in zip(events, audits, sources, snapshots):
            g = audit_group.create_group(ev['event_id'])
            g.attrs.update(audit, propagated_source=str(source), propagated_sha256=sha(source), snapshot=str(snapshot))
        e = h['e'][:]
        energy = h['specific_energy_j_kg'][:]/1e6
        ap = h['Q_au'][:]
        with np.errstate(invalid='ignore'):
            qwidth = np.nanquantile(ap, .975, axis=1)-np.nanquantile(ap, .025, axis=1)
        ewidth = np.quantile(energy, .975, axis=1)-np.quantile(energy, .025, axis=1)
        keep = (np.median(e, axis=1) >= 1) | (np.isfinite(qwidth) & (qwidth <= 20) & (ewidth <= 100))
        h['plot_keep'] = keep
        h['cometary_probability_bound'] = probability
        h['bound_sample_count'] = [np.count_nonzero(bound_mask(ev)) for ev in events]
        h['hyperbolic_sample_count'] = np.sum(e >= 1, axis=1)
        h.attrs['plot_selection'] = 'Median-hyperbolic or Q 95% width <=20 AU and energy 95% width <=100 km^2/s^2; display only'
        print('events',len(events),'samples',e.size,'bound samples',np.sum(e<1),'hyperbolic samples',np.sum(e>=1))
        print('all-bound ensembles',np.sum(np.all(e<1,axis=1)),'mixed',np.sum(np.any(e<1,axis=1)&np.any(e>=1,axis=1)))
        print('plot',sum(keep),'omitted',h['event_id'].asstr()[:][~keep])
        print('input hash mismatches',sum(not a['input_hash_matches'] for a in audits))
        print('methods',np.unique(h['uncertainty_method'].asstr()[:],return_counts=True))
        for row in rows:
            print(row['key'],row['n_events'],row['n_samples'],row['cometary_event_mean_fraction'])


if __name__ == '__main__':
    main()
