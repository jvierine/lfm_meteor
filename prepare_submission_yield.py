"""Current-catalogue duration and planning yields, not a seasonal flux model."""
from pathlib import Path
from datetime import datetime, timedelta, timezone
import hashlib
import h5py
import numpy as np

ROOT = Path(__file__).resolve().parent
PAPER = ROOT.parent / 'sanya_tristatic_paper'
MANIFEST = ROOT / 'results/tristatic_shrinking_orbits_current_20261107/orbits.h5'
CATALOG = ROOT / 'results/tristatic_cached_shrinking_20261029'
OUT = ROOT / 'results/submission_yield_20261107.h5'


def main():
    with h5py.File(MANIFEST) as h:
        events = h['event_id'].asstr()[:]
    starts, durations = [], []
    for event in events:
        with h5py.File(CATALOG / event / 'plot.h5') as h:
            times = h['time_ns'][:]
            starts.append(int(np.min(times)))
            durations.append((int(np.max(times))-int(np.min(times)))*1e-9)
    starts = np.asarray(starts, dtype=np.int64)
    durations = np.asarray(durations)
    # Detection-overview observation span, not the extrema of the selected fits.
    start = datetime.fromisoformat('2024-04-22T12:01:26.659+00:00')
    end = datetime.fromisoformat('2024-04-22T23:49:53.159+00:00')
    hours = (end-start).total_seconds()/3600
    offset = timedelta(hours=109.6222/15)
    solar_start, solar_end = start+offset, end+offset
    overlap_h = 0.
    day = solar_start.replace(hour=0, minute=0, second=0, microsecond=0)
    while day <= solar_end:
        lo, hi = max(solar_start, day+timedelta(hours=2)), min(solar_end, day+timedelta(hours=10))
        overlap_h += max(0., (hi-lo).total_seconds()/3600)
        day += timedelta(days=1)
    solar_hours = np.mod(starts/1e9/3600+109.6222/15, 24)
    count = int(np.sum((solar_hours >= 2) & (solar_hours < 10)))
    rate = count/overlap_h
    with h5py.File(OUT, 'w') as h:
        h.create_dataset('event_id', data=events, dtype=h5py.string_dtype())
        h['start_time_ns'] = starts
        h['duration_s'] = durations
        h.attrs.update(n_events=len(events), duration_mean_s=durations.mean(),
            duration_p95_s=np.quantile(durations,.95), observation_hours=hours,
            rate_per_hour=len(events)/hours, duty_1min_per_hour_rate=len(events)/hours/60,
            dawn_count=count, dawn_overlap_hours=overlap_h, dawn_rate_per_hour=rate,
            dawn_four_hours_per_day_one_minute_per_hour_annual=rate/60*4*365,
            start_utc=start.isoformat(), end_utc=end.isoformat(),
            time_convention='Mean local solar time: UTC + longitude/15; equation of time omitted',
            window='02:00--10:00 mean local solar time',
            selection_sha256=hashlib.sha256(MANIFEST.read_bytes()).hexdigest(),
            source_program=Path(__file__).read_text(),
            limitation='Detection-coverage span assumes continuous meteor-mode exposure; planning extrapolation, not seasonal yield')
        print({k:v for k,v in h.attrs.items() if k != 'source_program'})
    values = dict(tristaticEventDurationN=str(len(events)),
        tristaticEventDurationMeanS=f'{durations.mean():.3f}',
        tristaticEventDurationMedianS=f'{np.median(durations):.3f}',
        tristaticEventDurationPninetyfiveS=f'{np.quantile(durations,.95):.3f}')
    dawn = dict(dawnWindowFitCount=str(count), dawnWindowOverlapHours=f'{overlap_h:.2f}',
        dawnWindowFitRatePerHour=f'{rate:.1f}', dawnWindowMinutesPerFit=f'{60/rate:.1f}',
        dawnWindowOneSixtiethRatePerElapsedHour=f'{rate/60:.2f}')
    for filename, group in [('tristatic_event_duration_macros.tex',values),('dawn_window_yield_macros.tex',dawn)]:
        (PAPER/'tables'/filename).write_text('% Generated by prepare_submission_yield.py\n'+
            '\n'.join('\\newcommand{\\'+k+'}{'+v+'}' for k,v in group.items())+'\n')


if __name__ == '__main__':
    main()
