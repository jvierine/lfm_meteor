    above = np.asarray(row["above_states_gcrs"], dtype=np.float64)
    a_au = kepler[0, :] / AU_M
    e = kepler[1, :]
    inc = kepler[2, :]

    nominal_pos = above[0, :3]
    nominal_vel = above[0, 3:]
    along = nominal_vel / np.linalg.norm(nominal_vel)
    radial = nominal_pos / np.linalg.norm(nominal_pos)
    cross = radial - np.dot(radial, along) * along
    cross /= np.linalg.norm(cross)
    normal = np.cross(along, cross)
    delta = above[:, :3] - nominal_pos[None, :]
    sample_along_m = delta @ along
    sample_cross_m = delta @ cross
