def write_h5(path: str, rows: list[dict], args) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    string_dtype = h5py.string_dtype(encoding="utf-8")
    with h5py.File(path, "w") as h:
        h.attrs["script"] = "estimate_orbit_element_uncertainty.py"
        h.attrs["input_h5"] = args.input
        h.attrs["kernel"] = args.kernel
        h.attrs["samples_per_event"] = args.samples
        h.attrs["above_atmosphere_alt_km"] = args.above_atmosphere_alt_km
        h.attrs["above_atmosphere_model"] = "Backward central-gravity plus fitted drag using a simple exponential high-atmosphere density."
        h.attrs["orbit_propagator"] = "dasst.orbit_determination.rebound_od"
        h["event_id"] = np.asarray([r["event_id"] for r in rows], dtype=string_dtype)
        for key in rows[0]:
            if key in ("event_id", "kepler_sample", "above_states_gcrs", "above_states_no_drag_gcrs"):
                continue
            h[key] = np.asarray([r[key] for r in rows])
        g = h.create_group("kepler_samples")
        ag = h.create_group("above_atmosphere_gcrs_states")
        ng = h.create_group("above_atmosphere_no_drag_gcrs_states")
        for row in rows:
            g.create_dataset(row["event_id"], data=row["kepler_sample"], compression="gzip")
            ag.create_dataset(row["event_id"], data=row["above_states_gcrs"], compression="gzip")
            ng.create_dataset(row["event_id"], data=row["above_states_no_drag_gcrs"], compression="gzip")


def distribution_row(values: np.ndarray) -> tuple[float, float, float]:
    return (
        float(np.nanpercentile(values, 25.0)),
        float(np.nanpercentile(values, 50.0)),
        float(np.nanpercentile(values, 75.0)),
    )


def write_article_table(path: str, rows: list[dict]) -> None:
    metrics = [
        ("Semi-major axis std. (AU)", "a_au_std"),
        ("Eccentricity std.", "e_std"),
        ("Inclination std. (deg)", "inc_deg_std"),
        ("Argument of perihelion std. (deg)", "argp_deg_std"),
        ("Longitude of ascending node std. (deg)", "node_deg_std"),
    ]
    lines = [
        "% Auto-generated by /Users/jvi019/src/lfm_meteor/estimate_orbit_element_uncertainty.py",
        "\\begin{tabular}{@{}lrrr@{}}",
        "\\toprule",
        "Quantity & 25\\% & Median & 75\\% \\\\",
        "\\midrule",
    ]
    for label, key in metrics:
        q25, q50, q75 = distribution_row(np.asarray([r[key] for r in rows], dtype=np.float64))
        lines.append(f"{label} & {q25:.3g} & {q50:.3g} & {q75:.3g} \\\\")
    frac = np.asarray([r["interstellar_fraction_e_gt_1"] for r in rows], dtype=np.float64)
    q25, q50, q75 = distribution_row(frac)
    lines.append(f"Monte Carlo fraction with $e>1$ & {q25:.3g} & {q50:.3g} & {q75:.3g} \\\\")
    q25, q50, q75 = distribution_row(np.asarray([r["median_sanya_snr_db"] for r in rows], dtype=np.float64))
    lines.append(f"Median Sanya SNR (dB) & {q25:.3g} & {q50:.3g} & {q75:.3g} \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


