def kepler_text(kepler: np.ndarray) -> str:
    a_au = kepler[0, :] / AU_M
    e = kepler[1, :]
    inc = kepler[2, :]
    argp = kepler[3, :]
    node = kepler[4, :]
    nu = kepler[5, :]
    q = a_au * (1.0 - e)
    Q = a_au * (1.0 + e)
    a_j = 5.204
    with np.errstate(invalid="ignore"):
        tj = a_j / a_au + 2.0 * np.cos(np.deg2rad(inc)) * np.sqrt((a_au / a_j) * (1.0 - e**2.0))
    values = [
        ("a", a_au, "AU", 2),
        ("q", q, "AU", 3),
        ("Q", Q, "AU", 2),
        ("e", e, "", 3),
        ("i", inc, "deg", 1),
        ("T_J", tj, "", 2),
        (r"\omega", argp, "deg", 1),
        (r"\Omega", node, "deg", 4),
        (r"\nu", nu, "deg", 1),
    ]
    lines = ["Keplerian elements"]
    for name, arr, unit, ndigits in values:
        finite = np.asarray(arr, dtype=np.float64)
        mu = float(np.nanmean(finite))
        sig = circular_std_deg(finite) if unit == "deg" else float(np.nanstd(finite, ddof=1))
        fmt = f"{{:.{ndigits}f}}"
        suffix = f" {unit}" if unit else ""
        lines.append(f"${name}$ = {fmt.format(mu)} +/- {fmt.format(sig)}{suffix}")
    return "\n".join(lines)


