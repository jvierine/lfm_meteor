def main() -> None:
    args = parse_args()
    rng = np.random.default_rng(args.seed)
    fits = [fit for fit in load_fits(args.input) if fit.covariance_available]
    if args.only_event_id is not None:
        fits = [fit for fit in fits if fit.event_id == args.only_event_id]
    if args.start_index:
        fits = fits[args.start_index :]
    if args.max_events is not None:
        fits = fits[: args.max_events]
    if not fits:
        raise RuntimeError("No covariance-bearing fits found.")

    rows = []
    for idx, fit in enumerate(fits):
        print(f"[{idx + 1}/{len(fits)}] {fit.event_id}", flush=True)
        rows.append(process_event(fit, args, rng))

    write_summary_csv(args.summary_csv, rows)
    write_h5(args.output_h5, rows, args)
    write_article_table(args.article_table, rows)
    if args.make_example_plot:
        example = rows[0]
        if args.example_event_id is not None:
            matches = [row for row in rows if row["event_id"] == args.example_event_id]
            if matches:
                example = matches[0]
        make_example_plot(example, args.example_figure)
        print(f"wrote {args.example_figure}")
        print(f"wrote {os.path.splitext(args.example_figure)[0] + '.png'}")
    if args.make_snr_scatter_plot:
        make_snr_scatter_plot(rows, args.snr_scatter_figure)
        print(f"wrote {args.snr_scatter_figure}")
        print(f"wrote {os.path.splitext(args.snr_scatter_figure)[0] + '.png'}")
    if args.make_orbit_xy_plot:
        example = rows[0]
        if args.example_event_id is not None:
            matches = [row for row in rows if row["event_id"] == args.example_event_id]
            if matches:
                example = matches[0]
        make_orbit_xy_plot(example, args.orbit_xy_figure)
        print(f"wrote {args.orbit_xy_figure}")
        print(f"wrote {os.path.splitext(args.orbit_xy_figure)[0] + '.png'}")
    print(f"wrote {args.summary_csv}")
    print(f"wrote {args.output_h5}")
    print(f"wrote {args.article_table}")


if __name__ == "__main__":
    main()
